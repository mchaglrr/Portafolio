import requests, re, json, unicodedata, zipfile, os, datetime as dt
import numpy as np, pandas as pd, matplotlib.pyplot as plt, folium
from pyproj import Transformer
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score, confusion_matrix, ConfusionMatrixDisplay
from sklearn.neighbors import KNeighborsClassifier
from sklearn.model_selection import LeaveOneOut, cross_val_predict

"""## Fase A — Recolección y preparación
**Decisión metodológica:** en OSM la marca VIDRI puede tener muy pocos puntos. Por eso se extraen (1) todo nombre que contenga «vidri» y (2) comercios relacionados (vidrierías y ferreterías/materiales) del departamento de La Paz. Cada punto conserva su categoría para poder distinguir VIDRI del resto. No se inventa ningún dato faltante.
"""

DEPTO, LUGAR = "La Paz", "VIDRI"
FECHA = dt.date.today().isoformat()
CONSULTA = """[out:json][timeout:120];
area["ISO3166-2"="SV-PA"]->.a;
(
  nwr(area.a)["name"~"vidr[ií]",i];
  nwr(area.a)["shop"="glaziery"];
  nwr(area.a)["craft"="glaziery"];
  nwr(area.a)["shop"~"^(doityourself|hardware|trade)$"];
);
out center tags;"""

def overpass(q):
    for url in ["https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter"]:
        try:
            r = requests.post(url, data={"data": q}, timeout=150, headers={"User-Agent": "actividad-escolar-hotspots/1.0"})
            r.raise_for_status()
            return r.json()["elements"]
        except Exception as e:
            print("Falló", url, "->", e)
    raise RuntimeError("Overpass no respondió. Intenten de nuevo en unos minutos.")

elementos = overpass(CONSULTA)
filas = []
for e in elementos:
    t = e.get("tags", {})
    c = e if e["type"] == "node" else e.get("center", {})
    filas.append(dict(osm_id=f'{e["type"]}/{e["id"]}', name=t.get("name"), shop=t.get("shop"), craft=t.get("craft"),
                      latitude=c.get("lat"), longitude=c.get("lon"),
                      municipality=t.get("addr:city") or t.get("addr:municipality")))
raw = pd.DataFrame(filas)
raw.to_csv("vidri_la_paz_crudo.csv", index=False)
print(f"{len(raw)} elementos descargados el {FECHA} (fuente: OSM/Overpass, área: {DEPTO})")

def sin_tildes(s):
    return unicodedata.normalize("NFD", s if isinstance(s, str) else "").encode("ascii", "ignore").decode().lower()

def categoria(r):
    n = sin_tildes(r["name"])
    if re.search(r"\bvidri\b", n): return "VIDRI"
    if "vidr" in n or r["shop"] == "glaziery" or r["craft"] == "glaziery": return "Vidriería"
    return "Ferretería/materiales"

# --- Limpieza documentada ---
log = {"descargados": len(raw)}
df = raw.dropna(subset=["latitude", "longitude"]).copy()
log["sin_coordenadas"] = len(raw) - len(df)
fuera = ~df.latitude.between(13.0, 14.5) | ~df.longitude.between(-90.2, -87.6)
log["fuera_de_El_Salvador"] = int(fuera.sum())
df = df[~fuera].copy()
df["category"] = df.apply(categoria, axis=1)
n0 = len(df)
df = df.drop_duplicates("osm_id")
df["_k"] = df.name.fillna("").map(sin_tildes) + df.latitude.round(4).astype(str) + df.longitude.round(4).astype(str)
df = df.drop_duplicates("_k").drop(columns="_k").reset_index(drop=True)
df["etiqueta"] = df.name.fillna("(sin nombre en OSM)")
log["duplicados_eliminados"] = n0 - len(df)
log["sin_nombre_(se_conservan)"] = int(df.name.isna().sum())
log["sin_municipio_(se_deja_vacio)"] = int(df.municipality.isna().sum())
log["puntos_finales"] = len(df)
print(json.dumps(log, ensure_ascii=False, indent=2))
if len(df) < 6:
    raise ValueError("Hay menos de 6 puntos: K-Means y KNN no serían confiables. Documenten esto y amplíen el área/categorías (ver informe).")
df.to_csv("vidri_la_paz_limpio.csv", index=False)

diccionario = pd.DataFrame([
    ("osm_id", "Identificador del objeto en OSM", "OSM"), ("name", "Nombre del establecimiento (puede faltar)", "OSM"),
    ("category", "VIDRI / Vidriería / Ferretería/materiales (regla propia por nombre y etiquetas)", "Equipo"),
    ("shop, craft", "Etiquetas originales de OSM", "OSM"), ("latitude, longitude", "Coordenadas WGS84 (centro si es edificio)", "OSM"),
    ("municipality", "addr:city o addr:municipality; vacío si OSM no lo tiene", "OSM")], columns=["campo", "descripción", "origen"])
diccionario

# --- Análisis exploratorio ---
print("Puntos:", len(df)); print(df.category.value_counts())
fig, ax = plt.subplots(1, 2, figsize=(11, 4))
df.category.value_counts().plot.bar(ax=ax[0], color="#2a9d8f", title="Puntos por categoría")
for cat, g in df.groupby("category"): ax[1].scatter(g.longitude, g.latitude, label=cat, s=40)
ax[1].set(title="Distribución en La Paz", xlabel="longitud", ylabel="latitud"); ax[1].legend()
